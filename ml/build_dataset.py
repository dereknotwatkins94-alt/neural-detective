import csv
from pathlib import Path
# Каждый шаблон размечен по смыслу. В тесте — другие формулировки целиком,
# а не случайная половина подстановок тех же предложений.
train={
'contradiction':[
('Я был в {p} весь вечер.','Я не был в {p} в тот вечер.'),
('В {t} я вошел в кабинет.','В кабинет я вошел только в {u}.'),
('Я не видел {n} вчера.','Я видел {n} вчера.'),
('Дверь в {p} была закрыта.','Дверь в {p} была открыта.'),
('Я вернулся в {t}.','Я никогда не возвращался.'),
('В {t} я находился один в {p}.','В {t} я был вместе с гостем в {p}.'),
('В {t} я был в {p}.','В {t} я был на складе на другом конце города.'),
('Телефон был включен весь вечер.','Телефон был выключен весь вечер.'),
('Я не касался бокала.','Я держал этот бокал в руке.'),
('Я приехал на машине.','Я приехал пешком, машины у меня не было.')],
'consistent':[
('Я был в {p} в {t}.','В {t} я находился в {p}.'),
('Я не видел {n}.','С {n} я не встречался.'),
('Дверь в {p} была закрыта.','Вход в {p} был закрыт.'),
('Я вошел в {t} и ушел в {u}.','В {t} я пришел, в {u} покинул дом.'),
('Я ушел после ужина.','Когда ужин закончился, я ушел.'),
('Телефон был включен.','Мой телефон работал.'),
('Я разговаривал с {n}.','Собеседником был {n}.'),
('Я не возвращался в особняк.','Обратно в особняк я не приходил.'),
('Я был в {p}.','Я был в {p}.'),
('Я держал бокал в руке.','Мои отпечатки могли остаться на бокале.')],
'unknown':[
('Я был в {p} в {t}.','Телефон принадлежит {n}.'),
('Я ушел в {t}.','{n} ушел в {u}.'),
('Я не видел хозяина.','Дверь была закрыта.'),
('Финансовый отчет подписан.','На улице шел дождь.'),
('Я люблю читать в {p}.','Преступление совершено ночью.'),
('У меня есть машина.','В бокале найден яд.'),
('Я видел {n} вчера.','Камеры не работали.'),
('Кто-то был в {p}.','Я не знаю, кому звонил хозяин.'),
('Телефон был включен.','Я работал с документами.'),
('Охранник вышел во двор.','В кабинете стояли часы.')]
}
test={
'contradiction':[
('Ни разу за вечер я не посещал {p}.','Я все-таки заходил в {p} тем вечером.'),
('Встреча с {n} состоялась ровно в {t}.','Та встреча с {n} прошла ровно в {u}, а не в {t}.'),
('По моим словам, вход оставался закрытым.','На самом деле вход был открыт.'),
('Я утверждаю, что не брал телефон.','Признаюсь: я брал телефон.'),
('Все время в {p} никого кроме меня не было.','В {p} вместе со мной был {n}.')],
'consistent':[
('Мое прибытие записано в журнале в {t}.','Время моего прихода по журналу — {t}.'),
('Отрицаю, что посещал {p}.','Ни разу в {p} я не был.'),
('Мы с {n} были знакомы еще до ужина.','С {n} я познакомился раньше того ужина.'),
('После {t} я оставался в {p}.','{p} я не покидал после {t}.'),
('Я сделал копию отчета.','Копия отчета была изготовлена мной.')],
'unknown':[
('Собеседник помнит {n}.','Вещь обнаружили в {p}.'),
('Свет погас в {t}.','Пропали ли документы, неизвестно.'),
('Моя работа связана с охраной.','Последний звонок был в {u}.'),
('Я не прикасался к письму.','{n} не знает, где хранится ключ.'),
('В отчете названо имя {n}.','Кто совершил убийство, отчет не устанавливает.')]
}
values=[dict(p=p,n=n,t=t,u=u) for p,n,t,u in [
('библиотеке','Игоря','20:10','22:15'),('гостиной','Петра','19:25','21:40'),('гараже','Сергея','20:35','22:30'),
('кухне','Олега','18:15','23:10'),('кабинете','Романа','21:05','23:35'),('холле','Дениса','19:45','22:55')]]
rows=[]
for split,templates in [('train',train),('test',test)]:
    for category,pairs in templates.items():
        for i,(a,b) in enumerate(pairs):
            for j,v in enumerate(values if split=='train' else values[:4]):
                rows.append(dict(a=a.format(**v),b=b.format(**v),label=category,split=split,group=f'{split}_{category}_{i}'))
path=Path(__file__).resolve().with_name('dataset.csv')
with path.open('w',encoding='utf-8',newline='') as f:
    writer=csv.DictWriter(f,fieldnames=['a','b','label','split','group'])
    writer.writeheader()
    writer.writerows(rows)
print(f'{len(rows)} annotated pairs')
